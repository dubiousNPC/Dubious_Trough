#!/usr/bin/env python3
"""Import Immersive Travel Caravaner routes into a compact Lua module."""
import json, os, sys, glob

src, out = sys.argv[1], sys.argv[2]

routes, empty, stats = {}, [], []
for path in sorted(glob.glob(os.path.join(src, '*.json'))):
    stem = os.path.splitext(os.path.basename(path))[0]
    if stem.count('_') != 1:
        sys.exit('ambiguous filename: %s' % stem)
    origin, dest = stem.split('_')
    pts = json.load(open(path))
    if not pts:
        empty.append(stem)
        continue
    key = (origin.lower(), dest.lower())
    if key in routes:
        # The notes warn the same route can appear twice with differing point
        # counts when archives overlap. Keep the longer one.
        if len(pts) <= len(routes[key][1]):
            continue
    routes[key] = ((origin, dest), pts)
    stats.append((stem, len(pts)))

# Display names, first spelling wins (balmora_vivec is lower-case in the source
# while everything else is Title Case).
names = {}
for (ol, dl), ((o, d), _) in routes.items():
    names.setdefault(ol, o)
    names.setdefault(dl, d)

pairs = sorted(routes.keys())
total = sum(len(routes[k][1]) for k in pairs)

L = []
L.append('---@omw-context none')
L.append('--[[')
L.append('    caravans_routes.lua -- silt strider route geometry')
L.append('')
L.append('    GENERATED by tools/import_routes.py from Immersive Travel')
L.append('    (rfuzzo), MWSE/mods/rfuzzo/ImmersiveTravel/Caravaner/*.json.')
L.append('    Do not hand-edit; re-run the importer.')
L.append('')
L.append('    SILTSTRIDER_NOTES.md: "Take from [R]: ... the route point sets."')
L.append('    This is that, and nothing else from it -- none of its movement')
L.append('    code transfers, because that is written in 60fps frame steps.')
L.append('')
L.append('    SHAPE. Each route is ONE FLAT ARRAY of x,y,z triples rather than')
L.append('    a list of {x=,y=,z=} tables. 2000+ points as three-field tables')
L.append('    is thousands of table allocations at load for no gain: the')
L.append('    walker indexes by stride 3 and builds a vector only for the')
L.append('    point it is currently interpolating.')
L.append('')
L.append('    ONE DIRECTION ONLY. routes[origin][destination] exists for the')
L.append('    direction the source happened to ship; the walker traverses')
L.append('    backwards when asked for the other. That is not just a size')
L.append('    saving -- the source is genuinely one-directional in places')
L.append('    (there is a balmora_vivec and no vivec_balmora) and two of its')
L.append('    files are EMPTY (%s),' % ', '.join(empty) if empty else '    files are empty,')
L.append('    which the notes warn would teleport the strider to origin.')
L.append('    Reversal covers every one of those gaps.')
L.append('')
L.append('    Keys are LOWER CASE. names[] carries the display spelling.')
L.append('')
L.append('    %d routes, %d points.' % (len(pairs), total))
L.append(']]')
L.append('')
L.append('local M = {}')
L.append('')
L.append('-- Display spelling for each lower-cased key.')
L.append('M.names = {')
for k in sorted(names):
    L.append('    ["%s"] = "%s",' % (k, names[k]))
L.append('}')
L.append('')
L.append('-- routes[origin][destination] = { x,y,z, x,y,z, ... }')
L.append('M.routes = {')
last_o = None
for (ol, dl) in pairs:
    if ol != last_o:
        if last_o is not None:
            L.append('    },')
        L.append('    ["%s"] = {' % ol)
        last_o = ol
    pts = routes[(ol, dl)][1]
    flat = []
    for p in pts:
        flat += [int(round(p['x'])), int(round(p['y'])), int(round(p['z']))]
    # wrap at ~96 cols
    body, line = [], '        '
    for n in flat:
        tok = '%d,' % n
        if len(line) + len(tok) > 96:
            body.append(line.rstrip()); line = '        '
        line += tok + ' '
    if line.strip():
        body.append(line.rstrip())
    L.append('        ["%s"] = {   -- %d points' % (dl, len(pts)))
    L += body
    L.append('        },')
L.append('    },')
L.append('}')
L.append('')
L.append('return M')
open(out, 'w').write('\n'.join(L) + '\n')

print('routes: %d   points: %d' % (len(pairs), total))
print('dropped empty: %s' % (', '.join(empty) or 'none'))
print('places: %d' % len(names))
print('longest: %s' % ', '.join('%s=%d' % s for s in sorted(stats, key=lambda s: -s[1])[:3]))
