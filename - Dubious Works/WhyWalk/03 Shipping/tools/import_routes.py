#!/usr/bin/env python3
"""Import Immersive Travel Shipmaster routes into a compact Lua module.

usage: import_routes.py <ImmersiveTravel dir> scripts/WhyWalk/Shipping/shipping_routes.lua

<ImmersiveTravel dir> is the folder holding Shipmaster/ and services/
(MWSE/mods/rfuzzo/ImmersiveTravel in the Immersive Travel archive).

What it does, and why:
  * every route is kept in the direction its file gives; the walker reverses
    it when the other direction is asked for and has no file of its own;
  * file names are folded to lower case; a pair that appears twice keeps the
    longer file;
  * repeated points (zero-length segments) are removed, because a route walker
    cannot take a heading from a segment with no length;
  * a route with an OUT-AND-BACK SPIKE is dropped: a vertex where the course
    turns back on itself (over 150 degrees) between two segments that are each
    more than five times the route's median. Caravans' rule (longest segment
    over 10x the median) does not transfer to the sea: an open-water leg is
    legitimately long and straight, and that rule flagged four good routes
    (Gah Sadrith - Alt Bosara runs one 54,612-unit leg with a 3-degree bend at
    each end);
  * the vessel for each route is decided here, from services/Shipmaster.json:
    the first `override_mount` whose point list names both ends, else `mount`.
    That is Immersive Travel's own rule (main.lua), evaluated once at import
    instead of at every departure.
"""
import json, math, os, sys, glob, statistics

src, out = sys.argv[1], sys.argv[2]
svc = json.load(open(os.path.join(src, 'services', 'Shipmaster.json')))

def mount_for(a, b):
    for o in svc.get('override_mount', []):
        pts = [x.lower() for x in o['points']]
        if a in pts and b in pts:
            return o['id']
    return svc['mount']

def turn_deg(p, i):
    h1 = math.atan2(p[i][0] - p[i-1][0], p[i][1] - p[i-1][1])
    h2 = math.atan2(p[i+1][0] - p[i][0], p[i+1][1] - p[i][1])
    return abs(math.degrees((h2 - h1 + math.pi) % (2 * math.pi) - math.pi))

def spike(p):
    L = [math.dist(p[i][:2], p[i+1][:2]) for i in range(len(p) - 1)]
    if len(L) < 3:
        return None
    med = statistics.median(L)
    for i in range(1, len(p) - 1):
        if turn_deg(p, i) > 150 and L[i-1] > 5 * med and L[i] > 5 * med:
            return 'turns %.0f degrees at point %d between legs of %.0f and %.0f (median %.0f)' % (
                turn_deg(p, i), i, L[i-1], L[i], med)
    return None

routes, dropped, deduped, names = {}, [], 0, {}
for path in sorted(glob.glob(os.path.join(src, 'Shipmaster', '*.json'))):
    stem = os.path.splitext(os.path.basename(path))[0]
    if stem.count('_') != 1:
        sys.exit('ambiguous filename: %s' % stem)
    a, b = stem.split('_')
    raw = json.load(open(path))
    pts = []
    for q in raw:
        v = (round(q['x']), round(q['y']), round(q['z']))
        if pts and math.dist(v[:2], pts[-1][:2]) < 1:
            deduped += 1
            continue
        pts.append(v)
    key = (a.lower(), b.lower())
    names.setdefault(key[0], a); names.setdefault(key[1], b)
    if len(pts) < 2:
        dropped.append('%s -> %s (empty)' % key); continue
    why = spike(pts)
    if why:
        dropped.append('%s -> %s (%s)' % (key[0], key[1], why)); continue
    if key in routes and len(pts) <= len(routes[key]):
        continue
    routes[key] = pts

L = []
w = L.append
w('---@omw-context none')
w('--[[')
w('    shipping_routes.lua -- Shipmaster route geometry')
w('')
w('    GENERATED by tools/import_routes.py from Immersive Travel (rfuzzo),')
w('    MWSE/mods/rfuzzo/ImmersiveTravel/Shipmaster/*.json and')
w('    services/Shipmaster.json. Do not hand-edit; re-run the importer.')
w('')
w('    Each route: from/to (lower case), the vessel Immersive Travel assigns')
w('    to that pair, and ONE FLAT ARRAY of x,y,z triples. One direction per')
w('    file; the walker reverses a route when asked for the other way.')
w('')
w('    %d routes, %d points; %d repeated points removed.' % (
    len(routes), sum(len(p) for p in routes.values()), deduped))
if dropped:
    w('    Dropped at import:')
    for d in dropped:
        w('      ' + d)
w(']]')
w('')
w('local M = {}')
w('')
w('-- Display spelling for each lower-cased name.')
w('M.names = {')
for k in sorted(names):
    w('    [%s] = %s,' % (json.dumps(k), json.dumps(names[k])))
w('}')
w('')
w('M.routes = {')
for (a, b) in sorted(routes):
    p = routes[(a, b)]
    w('    { from = %s, to = %s, mount = %s,   -- %d points' % (
        json.dumps(a), json.dumps(b), json.dumps(mount_for(a, b)), len(p)))
    flat = [str(c) for q in p for c in q]
    for i in range(0, len(flat), 12):
        w('        ' + ', '.join(flat[i:i+12]) + ',')
    w('    },')
w('}')
w('')
w('return M')
open(out, 'w').write('\n'.join(L) + '\n')
print('%d routes written, %d dropped, %d repeated points removed' % (len(routes), len(dropped), deduped))
for d in dropped:
    print('  dropped: ' + d)
