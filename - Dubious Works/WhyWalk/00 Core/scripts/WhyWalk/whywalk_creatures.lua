    GENERATED by tools/gen_creatures.py from the compiled creature
    profile (creatures_all.csv: every CREA record across Morrowind,
    Tribunal, Bloodmoon, Tamriel Data and OAAB, joined to its mesh).
    Do not hand-edit; re-run the generator.

    WHAT EACH FIELD IS

    up        where the rider sits, in units above the creature's own
              origin. For a walker, 0.86 of the top of the collision box
              the engine builds from the mesh. For a flier, the BOTTOM
              of that box -- a netch's box starts 348 units up and its
              rider hangs under the bell rather than sitting on it.
              nil where the mesh was not available to measure.

    ride      false when the record sets the biped flag or the
              weapon/shield flag. A biped takes its animation from the
              NPC rig, and a weapon carrier has a Weapon Bone; neither
              is a mount. This is the record's own verdict, not a
              judgement about the model.

    fly       the record's Flies flag.

    THE SADDLE HEIGHT IS AN APPROXIMATION and the generator's own
    header says how good: it fits the four hand-measured ground mounts
    to within 12%. whywalk_shared.PROFILE still wins where it has an
    entry, because those came from the riding mods' own configs.

    SHARED SHAPES. Most creatures are variants of each other, so the
    geometry lives in SHAPES and each id holds an index into it.
