#!/usr/bin/env python3
"""gen_creatures.py -- bake the compiled creature profile into a Lua table.

    python3 tools/gen_creatures.py creatures_all.csv \
        > scripts/WhyWalk/whywalk_creatures.lua

WHAT THIS IS FOR

Three things WhyWalk currently works out at runtime, or cannot work out at all:

  1. WHERE THE RIDER SITS. `saddleFromBoundingBox` reads `getBoundingBox()` on
     first mount and derives an offset. The box it reads is the one the engine
     built from the mesh -- which is exactly what the compiled profile already
     measured, for 908 creatures, offline. A lookup is cheaper than a box read
     and a log line, and it can be CORRECTED per species where the derivation
     is wrong, which a formula cannot.

  2. WHETHER IT CAN BE RIDDEN AT ALL. A biped takes its animation from the NPC
     rig and a weapon-carrier has a Weapon Bone: neither reads as a mount.

  3. WHETHER THE BOX IS TRUSTWORTHY. 48 of 956 have no usable box here (33
     OAAB meshes ship in a BSA this audit could not open, 15 have no explicit
     Bounding Box and fall through to an autogenerated AABB). Those are
     omitted rather than guessed at, so the runtime falls back for exactly the
     creatures where falling back is right.

THE SADDLE HEIGHT

    up = SADDLE_FRACTION * box_top_z

Checked against every hand-measured saddle in whywalk_shared.PROFILE, each of
which came from the riding mod's own config rather than from this data:

    creature        measured   box top   up/top
    guar                 130     159.9    0.813
    kagouti              120     159.9    0.751
    nix-hound            110     115.6    0.951
    silt strider        1223    1322.2    0.925
    BM_frost_boar         95      76.2    1.246   <- excluded, see below
    netch_bull           200     768.4    0.260   <- flier, excluded
    skylamp               90     611.0    0.147   <- flier, excluded

0.86 is the mean of the four ground mounts and fits them to within 12%. That
sounds loose and it is: a kagouti's head rides higher above its back than a
nix-hound's, and no single fraction of a bounding box can know that. The
measured values stay in PROFILE and win; this is the figure for the other 900.

NOTE THAT THIS IS NOT AN IMPROVEMENT ON THE EXISTING HEURISTIC. `up = centre +
0.72 * halfSize.z` reduces to `0.86 * top` whenever the box bottom is at zero,
which is every ground creature -- the two formulas are the same thing written
twice, and the 0.72 fitted to one animal happened to be right. What the table
adds is the lookup instead of the read, the fliers handled separately, and a
place to put a corrected value.

FLIERS get `up = box_bottom_z` and `fly = true`. A netch's box starts 348
units up; its measured saddle of 200 is BELOW that, because the rider hangs
under the bell rather than sitting on it. The fraction is meaningless there,
so the bottom of the box is reported and the rider is placed relative to it.

BM_frost_boar is excluded from the fit because its measured saddle of 95 is
19 units ABOVE its box top of 76. Either the riding mod scales its boar or
that profile entry was never measured; either way it cannot constrain a fit.
"""
import csv
import collections
import sys

SADDLE_FRACTION = 0.86

# A box bottom above this counts as actually floating. The netch is at 348
# and the skylamp at 35; a cliff racer is at 0.
FLOAT_CLEARANCE = 20.0


def num(row, key):
    try:
        return float(row[key])
    except (TypeError, ValueError):
        return None


def main(argv):
    if not argv:
        sys.exit(__doc__.strip().split('\n')[2].strip())

    rows = list(csv.DictReader(open(argv[0], encoding='utf-8')))

    # ---- derive one entry per creature -----------------------------------
    entries = {}
    skipped_no_box = []
    for r in rows:
        rid = (r['id'] or '').strip().lower()
        if not rid:
            continue
        biped = r['biped'] == 'yes'
        weapon = r['weapon_shield'] == 'yes'
        flies = r['flies'] == 'yes'
        top = num(r, 'box_top_z')
        bottom = num(r, 'box_bottom_z')

        rideable = not (biped or weapon)

        if top is None:
            # No usable box. Still worth an entry when it is unrideable: that
            # verdict comes from the record, not the mesh, and is the half of
            # this table that does not need geometry.
            skipped_no_box.append(rid)
            if not rideable:
                entries[rid] = (None, False, flies)
            continue

        # A flier whose box starts at ground level is a flier in name only --
        # a cliff racer's box bottom is 0 and sitting at 0 would put the rider
        # at its feet. The bottom is only meaningful when the box actually
        # floats, so the walker rule covers the rest.
        if flies and bottom is not None and bottom > FLOAT_CLEARANCE:
            up = bottom
        else:
            up = SADDLE_FRACTION * top
        entries[rid] = (round(up), rideable, flies)

    # ---- share identical shapes ------------------------------------------
    # 956 creatures, far fewer distinct (up, rideable, fly) triples: every
    # kagouti variant is the same animal with different stats. A shape table
    # plus an index per id is a third of the size of the long form and reads
    # the same way at runtime.
    shapes = collections.OrderedDict()
    for rid in sorted(entries):
        key = entries[rid]
        if key not in shapes:
            shapes[key] = len(shapes) + 1       # Lua is 1-based

    out = []
    w = out.append
    w('---@omw-context none')
    w('--[[')
    w('    whywalk_creatures.lua -- ride position and rideability, per creature')
    w('')
    w('    GENERATED by tools/gen_creatures.py from the compiled creature')
    w('    profile (creatures_all.csv: every CREA record across Morrowind,')
    w('    Tribunal, Bloodmoon, Tamriel Data and OAAB, joined to its mesh).')
    w('    Do not hand-edit; re-run the generator.')
    w('')
    w('    WHAT EACH FIELD IS')
    w('')
    w('    up        where the rider sits, in units above the creature\'s own')
    w('              origin. For a walker, %s of the top of the collision box'
      % SADDLE_FRACTION)
    w('              the engine builds from the mesh. For a flier, the BOTTOM')
    w('              of that box -- a netch\'s box starts 348 units up and its')
    w('              rider hangs under the bell rather than sitting on it.')
    w('              nil where the mesh was not available to measure.')
    w('')
    w('    ride      false when the record sets the biped flag or the')
    w('              weapon/shield flag. A biped takes its animation from the')
    w('              NPC rig, and a weapon carrier has a Weapon Bone; neither')
    w('              is a mount. This is the record\'s own verdict, not a')
    w('              judgement about the model.')
    w('')
    w('    fly       the record\'s Flies flag.')
    w('')
    w('    THE SADDLE HEIGHT IS AN APPROXIMATION and the generator\'s own')
    w('    header says how good: it fits the four hand-measured ground mounts')
    w('    to within 12%. whywalk_shared.PROFILE still wins where it has an')
    w('    entry, because those came from the riding mods\' own configs.')
    w('')
    w('    SHARED SHAPES. Most creatures are variants of each other, so the')
    w('    geometry lives in SHAPES and each id holds an index into it.')
    w(']]')
    w('')
    w('local M = {}')
    w('')
    w('-- { up, ride, fly }')
    w('M.SHAPES = {')
    for (up, ride, fly), _ in shapes.items():
        w('    { up = %s, ride = %s, fly = %s },'
          % ('nil' if up is None else up,
             'true' if ride else 'false',
             'true' if fly else 'false'))
    w('}')
    w('')
    w('-- record id (lower case) -> index into SHAPES')
    w('M.INDEX = {')
    line = '   '
    for rid in sorted(entries):
        piece = ' ["%s"]=%d,' % (rid, shapes[entries[rid]])
        if len(line) + len(piece) > 78:
            w(line)
            line = '   '
        line += piece
    if line.strip():
        w(line)
    w('}')
    w('')
    w('M.COUNT = %d' % len(entries))
    w('')
    w('---Everything known about a creature record, or nil if it is not in the')
    w('---compiled profile. The caller decides what to do with a nil `up`.')
    w('---@param recordId string|nil')
    w('---@return table|nil { up, ride, fly }')
    w('function M.get(recordId)')
    w('    if type(recordId) ~= "string" then return nil end')
    w('    local i = M.INDEX[recordId:lower()]')
    w('    return i and M.SHAPES[i] or nil')
    w('end')
    w('')
    w('return M')

    sys.stdout.write('\n'.join(out) + '\n')

    n_ride = sum(1 for v in entries.values() if v[1])
    sys.stderr.write(
        'generated %d creature(s), %d distinct shape(s)\n'
        '  rideable %d, barred %d\n'
        '  %d row(s) had no usable box; %d of those were kept for their flags\n'
        % (len(entries), len(shapes), n_ride, len(entries) - n_ride,
           len(skipped_no_box),
           sum(1 for rid in skipped_no_box if rid in entries)))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
